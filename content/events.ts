export function eventEnd(event: Concert) {
  return event.end ?? event.start;
}

export function upcomingEvents(now = new Date()) {
  return events
    .filter((event) => isUpcoming(eventEnd(event), now))
    .sort((a, b) => parseIsoDate(a.start).date.getTime() - parseIsoDate(b.start).date.getTime());
}

export function nearestEvent(now = new Date()) {
  return upcomingEvents(now)[0] ?? events[0];
}

export function getEvent(slug: string) {
  return events.find((event) => event.slug === slug);
}
